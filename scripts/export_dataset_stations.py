"""Generate src/datasetStations.ts: the places that are actually in the training dataset (55 USGS gauges).

Names/coordinates come from data/large/metadata/station_metadata.csv (USGS NWIS). The five rivers that already had
hand-tuned simulation presets keep their original ids so those presets still apply.

Usage: python -m scripts.export_dataset_stations
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import pandas as pd

FIPS = {'01': 'Alabama', '02': 'Alaska', '04': 'Arizona', '05': 'Arkansas', '06': 'California', '08': 'Colorado', '09': 'Connecticut',
        '10': 'Delaware', '11': 'District of Columbia', '12': 'Florida', '13': 'Georgia', '15': 'Hawaii', '16': 'Idaho', '17': 'Illinois',
        '18': 'Indiana', '19': 'Iowa', '20': 'Kansas', '21': 'Kentucky', '22': 'Louisiana', '23': 'Maine', '24': 'Maryland', '25': 'Massachusetts',
        '26': 'Michigan', '27': 'Minnesota', '28': 'Mississippi', '29': 'Missouri', '30': 'Montana', '31': 'Nebraska', '32': 'Nevada',
        '33': 'New Hampshire', '34': 'New Jersey', '35': 'New Mexico', '36': 'New York', '37': 'North Carolina', '38': 'North Dakota',
        '39': 'Ohio', '40': 'Oklahoma', '41': 'Oregon', '42': 'Pennsylvania', '44': 'Rhode Island', '45': 'South Carolina', '46': 'South Dakota',
        '47': 'Tennessee', '48': 'Texas', '49': 'Utah', '50': 'Vermont', '51': 'Virginia', '53': 'Washington', '54': 'West Virginia',
        '55': 'Wisconsin', '56': 'Wyoming'}
LEGACY = {  # original map rivers: keep ids/names so river-specific presets keep working
    '01646500': ('potomac', 'Little Falls', 'Potomac River'), '07010000': ('mississippi', 'St. Louis', 'Mississippi River'),
    '08158000': ('colorado', 'Austin', 'Colorado River'), '02087500': ('neuse', 'Near Clayton', 'Neuse River'),
    '11425500': ('sacramento', 'Verona', 'Sacramento River')}
STATES = {'AL','AK','AZ','AR','CA','CO','CT','DE','DC','FL','GA','HI','ID','IL','IN','IA','KS','KY','LA','ME','MD','MA','MI','MN','MS','MO','MT','NE','NV','NH','NJ','NM','NY','NC','ND','OH','OK','OR','PA','RI','SC','SD','TN','TX','UT','VT','VA','WA','WV','WI','WY'}
CONNECT = {'at', 'near', 'nr', 'below', 'bl', 'blw', 'above', 'abv', 'a'}
WORD = {'r': 'River', 'rv': 'River', 'bl': 'below', 'blw': 'below', 'nr': 'near', 'abv': 'above', 'a': 'at', 'at': 'at', 'near': 'near',
        'below': 'below', 'above': 'above', 'of': 'of', 'in': 'in', 'br': 'Branch', 'nw': 'Northwest', 'ne': 'Northeast', 'st.': 'St.', 'st': 'St.'}


def tidy(raw: str) -> tuple[str, str]:
    """Return (river, place) from a USGS station name; a trailing 2-letter state is kept uppercase."""
    toks = re.sub(r'\s+', ' ', raw.replace(',', ' ,')).strip().split(' ')
    state = None
    if len(toks) > 1 and len(toks[-1].strip('.')) == 2 and toks[-1].strip('.').isalpha() and toks[-1].strip('.').upper() in STATES:
        state = toks.pop().strip('.').upper()
        if toks and toks[-1] == ',':
            toks.pop()
    mapped = []
    for t in toks:
        key = t.lower().strip('.')
        mapped.append(WORD.get(key, t.capitalize() if t.isupper() or t.islower() else t))
    out = ' '.join(mapped).replace(' ,', ',').rstrip(',')
    words = out.split(' ')
    cut = next((i for i, w in enumerate(words) if w.lower() in {'at', 'near', 'below', 'above'} and i > 0), None)
    river = ' '.join(words[:cut]) if cut else out
    place = ' '.join(words[cut + 1:]) if cut else out
    place = place.rstrip(',') or out
    return river.rstrip(','), f'{place}, {state}' if state else place


def main() -> None:
    meta = pd.read_csv('data/large/metadata/station_metadata.csv', dtype=str)
    train = pd.read_csv('data/large/train/train.csv', dtype={'station_id': str}, usecols=['station_id', 'drainage_area_sqmi'])
    area = train.groupby('station_id').drainage_area_sqmi.first()
    rows = []
    for r in meta.itertuples():
        river, place = tidy(r.station_name)
        sid = LEGACY.get(r.station_id, (r.station_id, place, river))
        rows.append({'id': sid[0], 'name': sid[1], 'river': sid[2], 'region': f"{FIPS.get(r.state, 'United States')}, United States",
                     'lat': round(float(r.latitude), 4), 'lon': round(float(r.longitude), 4), 'usgs': r.station_id,
                     'legacy': r.station_id in LEGACY, 'area': float(area.get(r.station_id, 0))})
    rows.sort(key=lambda x: (not x['legacy'], x['river'].lower(), x['name'].lower()))
    body = ',\n'.join('  ' + json.dumps({k: v for k, v in x.items() if k not in ('legacy', 'area')}, ensure_ascii=False) for x in rows)
    Path('src/datasetStations.ts').write_text(
        "// Generated by scripts/export_dataset_stations.py from the training-data station metadata. Do not edit by hand.\n"
        "import type { Station } from './data';\n\n"
        f"/** The {len(rows)} USGS gauges the discharge model was trained on. */\nexport const datasetStations: Station[] = [\n{body}\n];\n", encoding='utf-8')
    print(len(rows), 'stations written')
    for x in rows[:8] + rows[-4:]:
        print(f"  {x['id']:12s} | {x['river']:34s} | {x['name']:30s} | {x['region']}")


if __name__ == '__main__':
    main()
