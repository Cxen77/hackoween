"""Generate src/indiaStations.ts from server/india_stations.json (Indian gauges with a LIVE NWIC discharge feed).

These are new rivers: none of them is in the model's training data. Run scripts/build_india_registry.py first.

Usage: python -m scripts.export_india_stations
"""
from __future__ import annotations

import json
from pathlib import Path


def main() -> None:
    reg = json.loads(Path('server/india_stations.json').read_text(encoding='utf-8'))['stations']
    reg.sort(key=lambda s: (str(s['river']).lower(), s['station'].lower()))
    rows = []
    for s in reg:
        river = str(s['river']).strip()
        rows.append({'id': s['key'], 'name': s['station'].title() if s['station'].isupper() else s['station'],
                     'river': river if river.lower().endswith(('river', 'nadi')) else f'{river} River',
                     'region': f"{s['state']}, India", 'lat': round(s['lat'], 4), 'lon': round(s['lon'], 4), 'nwic': s['key'], 'newRiver': True})
    body = ',\n'.join('  ' + json.dumps(r, ensure_ascii=False) for r in rows)
    Path('src/indiaStations.ts').write_text(
        "// Generated by scripts/export_india_stations.py from the NWIC live-feed registry. Do not edit by hand.\n"
        "import type { Station } from './data';\n\n"
        f"/** {len(rows)} Indian river gauges with current NWIC discharge. New rivers: not in the model's training data. */\n"
        f"export const indiaStations: Station[] = [\n{body}\n];\n", encoding='utf-8')
    print(len(rows), 'Indian live-feed stations written')


if __name__ == '__main__':
    main()
