"""Generate src/indiaStations.ts from server/india_stations.json (Indian gauges with a LIVE NWIC discharge feed).

These are new rivers: none of them is in the model's training data. Run scripts/build_india_registry.py first.
The registry holds 40 gauges on only 8 rivers. To keep the monitored list readable:
  * each entry is labelled by place ("Narmada at Handia"), not just the river name, so rivers do not look repeated;
  * at most MAX_PER_RIVER gauges per river are listed (largest recent flow first). The model test (india_live_test.json)
    still covers all registry gauges.
The portal tags some Mizoram records "Duplicate-Kolodyne"; that is a data label, the river is the Kolodyne.

Usage: python -m scripts.export_india_stations
"""
from __future__ import annotations

import json
import re
from pathlib import Path

MAX_PER_RIVER = 4


def clean_river(name: str) -> str:
    name = re.sub(r'^\s*duplicate[-\s]*', '', str(name), flags=re.I).strip()
    name = re.sub(r'\s+river$', '', name, flags=re.I)
    return name.title() if name.isupper() or name.islower() else name


def clean_place(name: str) -> str:
    name = name.strip()
    return name.title() if name.isupper() or name.islower() else name


def main() -> None:
    reg = json.loads(Path('server/india_stations.json').read_text(encoding='utf-8'))['stations']
    by_river: dict[str, list[dict]] = {}
    for s in reg:
        by_river.setdefault(clean_river(s['river']), []).append(s)
    rows = []
    for river, items in sorted(by_river.items()):
        for s in sorted(items, key=lambda x: -x['recent_mean_m3s'])[:MAX_PER_RIVER]:
            place = clean_place(s['station'])
            rows.append({'id': s['key'], 'name': f"{s['state']} · {river} basin", 'river': f'{river} at {place}',
                         'region': f"{s['state']}, India", 'lat': round(s['lat'], 4), 'lon': round(s['lon'], 4), 'nwic': s['key'], 'newRiver': True})
    body = ',\n'.join('  ' + json.dumps(r, ensure_ascii=False) for r in rows)
    Path('src/indiaStations.ts').write_text(
        "// Generated by scripts/export_india_stations.py from the NWIC live-feed registry. Do not edit by hand.\n"
        "import type { Station } from './data';\n\n"
        f"/** {len(rows)} Indian river gauges (of {len(reg)} in the registry, max {MAX_PER_RIVER} per river) with current NWIC discharge. New rivers: not in the training data. */\n"
        f"export const indiaStations: Station[] = [\n{body}\n];\n", encoding='utf-8')
    print(len(rows), 'listed of', len(reg), 'registry gauges;', len(by_river), 'rivers:', {k: len(v) for k, v in sorted(by_river.items())})


if __name__ == '__main__':
    main()
